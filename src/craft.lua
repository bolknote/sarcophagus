function craft_ini ()

	if game.craft then

		craft_reset ()

		if is_pressed('lshift') then
			craft.multitem = true
		end

		craft_itemsget ()
		craft_str ()

		if craft.str~="" then
			game.craft = true
		end

	end

end



function craft_reset ()
	craft.pointer = 1
	craft.item_recipies = {}
	craft.len = 0
	craft.singleitem = nil
	craft.multitem = nil
end


function craft_up ()
	craft.pointer = craft.pointer - 1
	if craft.pointer < 1 then
		craft.pointer = #craft.item_recipies
	end
end

function craft_down ()
	craft.pointer = craft.pointer + 1
	if craft.pointer > #craft.item_recipies then
		craft.pointer = 1
	end
end

function craft_remove (i,keep)

	local remove
	local a = in_array_i (pl.inv, i)

	if a==nil then 
		
		a = in_array_i (world[pl.yt][pl.xt].i, i)	

		if keep==nil then
			remove = inv_ground_remove (pl.xt, pl.yt, a)
		else

			if world[pl.yt][pl.xt].i then
				local item = world[pl.yt][pl.xt].i[a]

				if item and item.tool and item.tool.crafthit then
					item.t = item.t - item.tool.crafthit
				end
			end
		end

	else
		
		a = in_array_i (pl.inv, i)

		if keep==nil then
			remove = inv_remove (a)
		else
			local item = pl.inv[a]
			if item and item.tool and item.tool.crafthit then
				item.t = item.t - item.tool.crafthit
			end
		end

	end

	return remove

end

function craft_do (i)

	craft.dura = {}
	craft.itemst = tablecopy (craft.items)
	local r = craft.recipies[i]
	local str,can = str_recipie (i)

	if can then

		--remove items
		for k,v in pairs(r.items) do
			for ir=1,v do
				local it = (craft_remove (k))
				craft.dura[it.i] = it.t
			end
		end

		
		if r.tools then for k,v in pairs(r.tools) do
		
			for kk,vv in pairs (craft.items) do

				local it = item[kk]

				if it.tool and it.tool[k] and it.tool[k]>=v then
					craft_remove (kk,true)
					break	
				end

			end

		end end


		--hidden result
		if r.result_h then
			for i,v in ipairs(r.result_h) do
				inv_add (item_make (v))
			end
		end

		--add items
		if r.result then for k,v in pairs(r.result) do
			for ir=1,v do
				local itm = item_make (k)

				achi_trigger ('on_craft','i'..k)

				if r.ondone then
					itm = r.ondone(itm)
				end
				
				inv_add (itm)
			end
		end
		end

		--give block
		if r.result_b then
			pl.iscarry = createblock (r.result_b)
			achi_trigger ('on_craft','b'..r.result_b)
		end

		sound_add ('craft',43)

		pl.unrest = pl.unrest + time.h*r.h + time.min*r.m --todo
		pl.unrest = pl.unrest * (pl.craftspeed or 1)

		player_score (2*pl.unrest/time.h)

		game.craft = false

	else

		game.shaken = 50

	end



end


function craft_str ()

	local s_ok =   "{#e8b796ff}"
	local s_miss = "{#e43b44ff}"
	local s_misslil = "{#d87644ff}"
	local s_sel  = "{#3e8948ff}"
	local s_n    = "{#ffffffff}"
	
	craft.cando = {}

	craft.str = ""
	craft.strinfo = ""
	
	if craft.multitem == true then
		craft_items_recipies ({block = craft.reqblock})
		craft.multitem = true
	else
		craft.singleitem = true
		if pl.inv[pl.invselect] and pl.inv[pl.invselect].i and craft.multitem == nil then
			item_unlock (pl.inv[pl.invselect].i)
			craft_item_recipies (pl.inv[pl.invselect].i)
		end
	end

	--sorting
	function craft_item_sort (k1,k2)
		local re,can,unlocked = str_recipie (k1)
		local re2,can2,unlocked2 = str_recipie (k2)
		local a1 = 0
		local a2 = 0

		if can then a1 = a1+2 end
		if can2 then a2 = a2+2 end
		if unlocked then a1 = a1 - 1 end
		if unlocked2 then a2 = a2 - 1 end

		if a1~=a2 then
			return a1>a2		
		else
			return re<re2
		end
	end

	table.sort (craft.item_recipies,craft_item_sort)




	if #craft.item_recipies>0 then

		local cnt = 0
		for k,v in pairs(craft.item_recipies) do
			
			if cnt>0 then
				craft.str = craft.str.."\n"
			end
			
			local re,can,unlocked = str_recipie (v)

			
			if craft.pointer==k then

				--info on future item
				if craft.recipies[v].result then
					for k,v in pairs(craft.recipies[v].result) do
						
						local info = msg.item[k].craftinfo or msg.item[k].info

						if info and info~="" then
							craft.strinfo = craft.strinfo..message (msg.game[7], {[1] = msg.item[k].name, [2] = info})
							--cnt = cnt + 2
						end

						if diet_info (item_make(k)) then
							craft.strinfo = craft.strinfo.."\n"..diet_info (item_make(k))
							--cnt = cnt + 2
						end
  
						local t = draw_tool (item[k],"",0,"  ")

						if t~="" then
							craft.strinfo = craft.strinfo.."  "..t
						end

						craft.strinfo = craft.strinfo.."\n"


					end
				end

				if craft.recipies[v].result_b and (msg.stone[craft.recipies[v].result_b].info or msg.stone[craft.recipies[v].result_b].craftinfo) then
					craft.strinfo = craft.strinfo..message (msg.game[7], {[1] = msg.stone[craft.recipies[v].result_b].name, [2] = (msg.stone[craft.recipies[v].result_b].craftinfo or msg.stone[craft.recipies[v].result_b].info)}).."\n"
					--cnt = cnt + 2
				end


				if can then
					craft.str = craft.str..s_sel.."» "
				else
					craft.str = craft.str..s_miss.."» "
				end

			else
				craft.str = craft.str.."  "..s_ok
			end

			
			craft.str = craft.str..re


			cnt = cnt + 1
		end

		craft.len = cnt+7
	
	else
		-- no recipies
		craft.str = msg.game[40]
	end


	

	if craft.str ~= "" then

		if craft.singleitem == true then
			if pl.inv[pl.invselect] then
				craft.str = message (msg.craft[1],{[1] = msg.item[pl.inv[pl.invselect].i].name})..craft.str
			end
		else
			craft.str = msg.craft[2]..craft.str
		end

		if craft.strinfo and craft.strinfo~="" then
			craft.str = craft.str.."\n\n"..craft.strinfo
			--craft.len = craft.len + 2
		end

		craft.str = craft.str..msg.craft[3]

	end

	return

end


