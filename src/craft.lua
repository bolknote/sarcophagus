				local it = item[kk]

				if it.tool and it.tool[k] and it.tool[k]>=v then

					toolfound = true

				end

			end

				if v==1 then
				
					if toolfound then
						str = str..craft_tool_tag(k)
					else
						str = str..s_miss..craft_tool_tag(k)..s_n
						cando = nil
					end

				else

					if toolfound then
						str = str..craft_tool_tag(k)..":"..v
					else
						str = str..s_miss..craft_tool_tag(k)..":"..v..s_n
						cando = nil
					end
			
				end

			end 




		end

		str = str..")"

	end


	str = str.." "..s_time..r.h..":"..string.rep ("0",2-string.len (r.m))..r.m
	str = str..s_g.." ]"

