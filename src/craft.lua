function str_recipie (i)
	
	local s_ok =   		"{#e8b796ff}"
	local s_miss =  	"{#e43b44ff}"
	local s_misslil = 	"{#d87644ff}"
	local s_sel  = 		"{#3e8948ff}"
	local s_n    = 		"{#ffffffff}"
	local s_g    = 		"{#5a6988ff}"
	local s_time =		"{#8b9bb4ff}"
	

	
	local str = ""
	local cando = true
	local unlocked = nil
	local r = craft.recipies[i]
	local cnt = 0

	--result
	if r==nil then return '' end

	if r.result then for k,v in pairs(r.result) do
		
		if cnt>0 then
			str = str.." + "
		end
		
		local s = ""

		str = str..msg.item[k].name
		
		if v>1 then
			str = str.." ×"..v
		end

		cnt = cnt + 1

	end end


	-- result (block)
	if r.result_b then

		if r.result then
			str = str.." + "
		end

		str = str..msg.stone[r.result_b].name
	end



	--str = str..s_g.." ←--[ "
	str = str..s_g.." "..string.rep (" ",30-utf8.len (str)).."←[ "
	


	--items
	local cnt = 0
	local sa = {}
	local str2 = str
	
	if r.items then for k,v in pairs(r.items) do

		str = ""
		local ty = "A"
		
		-- has item
		if craft.items[k] and craft.items[k]>=v then
			str = str..s_ok
		else
			
			if craft.items[k] then
				str = str..s_misslil
				ty = "B"
			else
				str = str..s_miss
				ty = "C"
			end

			cando = nil
		end


		if pl.unlock_i[k] or game.dbg[2] then
			str = str..msg.item[k].name..s_ok
		else
			unlocked = true
			str = str..'{#b86f50ff}'..mystify(msg.item[k].name)..s_ok
			cando = nil
			ty = "D"
		end
		

		if v>1 then

			if craft.items[k] and craft.items[k]>=v then
				str = str..s_n
			else
				if craft.items[k] and craft.items[k] then
					str = str..s_misslil
				else
					str = str..s_miss
				end
			end

			--mult
			str = str.." ×"..v..s_ok
		end

		cnt = cnt + 1

		table.insert (sa, {s = str, ty = ty..msg.item[k].name})

	end 
	end


	str = str2

	table.sort (sa, function (k1,k2) return k1.ty<k2.ty end)

	for i,v in ipairs(sa) do
		if i>1 then
			str = str..s_n.." + "
		end

		str = str..v.s
	end


	

	if r.tools or r.block then 

		str = str..s_n..msg.craft.requires

		local b = readmap (pl.xt, pl.yt,"b")

